#!/bin/sh
# VESPER 2: build the firmware with fm1-base.
#   JIELI_TOOLCHAIN=/path/to/jieli-linux-toolchains AC79_SDK=/path/to/ac79-sdk tools/build.sh [--release X.Y.Z] [--host]
# AC79_SDK: JieLi's AC79 SDK (base/bsp/tools/get_sdk.sh fetches it; tools/sdk_from_fwsc.py takes them from a Felucca-family .fwsc). The package carries three of its files
# (the SPL and two configuration blocks); with any other copy of them the package is refused here, so nothing
# that could not start ever reaches an FM-1.
set -e
cd "$(dirname "$0")/.."
case "$*" in *-test*|*--host*) t=1 ;; *) t=0 ;; esac   # test builds show the audio load in the header
printf '/* generated by tools/build.sh */\n#define VESPER_TEST %s\n' "$t" > app/vesper/build_flags.h
# VESPER's look on the update screens (fm1-base's update steps, felucca-bsp's loader): colours and words only,
# applied for the build and taken out after it, so the base's own tree stays as pinned
git -C base apply ../tools/update-screen.patch
git -C base apply ../tools/identity.patch
git -C base/bsp apply ../../tools/loader-screen.patch
unpatch() { git -C base/bsp apply -R ../../tools/loader-screen.patch; git -C base apply -R ../tools/update-screen.patch; git -C base apply -R ../tools/identity.patch; }
trap unpatch EXIT
out=$(python3 base/tools/build.py app "$@" 2>&1) || { echo "$out"; exit 1; }
echo "$out" | grep -v '^font '
if echo "$out" | grep -q "warning: SDK"; then
    for f in app/build/*.fwsc; do [ -f "$f" ] && mv "$f" "${f%.fwsc}.NOT-FOR-HARDWARE"; done
    echo "build.sh: AC79_SDK is not JieLi's AC79NN_SDK_V1.2.1: the package is NOT for an FM-1 (renamed .NOT-FOR-HARDWARE)" >&2
    exit 2
fi
